/* ST-LAB (ESP32) - Example Code
 LAB03 : Buzzer/PWM
*/
#define BUZZER_PIN 5 // กำหนดขา GPIO 5 สำหรับต่อ Buzzer
// ESP32 ใช้โมดูล LEDC สำหรับสร้างสัญญาณ PWM (ใช้สร้างเสียงได้)
const int PWM_CH = 0; // เลือกช่อง PWM หมายเลข 0
const int PWM_RES = 8; // ความละเอียด PWM 8 บิต (ค่าดิวตี้ไซเคิล 0–255)
const int PWM_DUTY = 128; // กำหนดดิวตี้ไซเคิล 128 = ประมาณ 50%

void setup()
{ // ทำงานครั้งเดียวเมื่อเปิดเครื่องหรือรีเซตบอร์ด
Serial.begin(115200); // เริ่มต้นการสื่อสาร Serial ที่ความเร็ว 115200 bps
ledcSetup(PWM_CH, 2000, PWM_RES); // ตั้งค่า PWM ช่องที่ 0 เริ่มต้นที่ 2 kHz ความละเอียด 8 บิต
ledcAttachPin(BUZZER_PIN, PWM_CH); // ผูกขา GPIO5 เข้ากับช่อง PWM ที่กำหนด
Serial.println("LAB03: Buzzer PWM Started"); // แสดงข้อความเริ่มต้นบน Serial Monitor
} // จบฟังก์ชัน setup()

void beep(int freq, int ms)
{ // ฟังก์ชันสร้างเสียงตามความถี่ (Hz) และระยะเวลา (ms)
ledcWriteTone(PWM_CH, freq); // ตั้งค่าความถี่ของสัญญาณ PWM ตามค่าที่ส่งมา
ledcWrite(PWM_CH, PWM_DUTY); // กำหนดดิวตี้ไซเคิลเพื่อให้เกิดเสียง (ความดังประมาณ 50%)
delay(ms); // ให้เสียงดังตามระยะเวลาที่กำหนด (มิลลิวินาที)
ledcWrite(PWM_CH, 0); // ตั้งดิวตี้ไซเคิลเป็น 0 เพื่อหยุดเสียง
} // จบฟังก์ชัน beep()

void loop()
{ // ทำงานวนซ้ำตลอดเวลาที่บอร์ดยังเปิดอยู่
// เล่นเสียงเรียงลำดับความถี่ (คล้ายโน้ตดนตรี)
beep(880, 120); // เล่นเสียงความถี่ 880 Hz นาน 120 ms
beep(988, 120); // เล่นเสียงความถี่ 988 Hz นาน 120 ms
beep(1047, 120); // เล่นเสียงความถี่ 1047 Hz นาน 120 ms
delay(500); // เว้นช่วงเงียบ 500 ms ก่อนเริ่มรอบใหม่
} // จบฟังก์ชัน loop()