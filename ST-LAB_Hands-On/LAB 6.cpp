/* ST-LAB (ESP32) - Example Code
 LAB06 : DHT11 Sensor
*/
#include <DHT.h> // เรียกใช้งานไลบรารีสำหรับเซนเซอร์ DHT
#define DHT_PIN 32 // กำหนดขา GPIO32 สำหรับเชื่อมต่อขา DATA ของ DHT11
#define DHT_TYPE DHT11 // กำหนดชนิดของเซนเซอร์เป็น DHT11
DHT dht(DHT_PIN, DHT_TYPE); // สร้างออบเจ็กต์ dht เพื่อควบคุมและอ่านค่าจากเซนเซอร์

void setup()
{ // ทำงานครั้งเดียวเมื่อเปิดเครื่องหรือรีเซตบอร์ด
Serial.begin(115200); // เริ่มต้นการสื่อสาร Serial ที่ความเร็ว 115200 bps
dht.begin(); // เริ่มต้นการทำงานของเซนเซอร์ DHT11
Serial.println("LAB06: DHT11 Started"); // แสดงข้อความเริ่มต้นบน Serial Monitor
} // จบฟังก์ชัน setup()

void loop()
{ // ทำงานวนซ้ำตลอดเวลาที่บอร์ดยังทำงานอยู่
float h = dht.readHumidity(); // อ่านค่าความชื้นสัมพัทธ์ (%RH)
float t = dht.readTemperature(); // อ่านค่าอุณหภูมิ (องศาเซลเซียส)
if (isnan(h) || isnan(t))
{ // ตรวจสอบว่าค่าที่อ่านได้เป็นตัวเลขหรือไม่ (อ่านสำเร็จหรือไม่)
Serial.println("DHT read failed!"); // แจ้งเตือนว่าอ่านค่าไม่สำเร็จ
delay(1000); // หน่วงเวลา 1 วินาทีก่อนลองอ่านใหม่
return; // ออกจาก loop รอบนี้ แล้วเริ่มรอบใหม่
} // จบเงื่อนไขตรวจสอบความผิดพลาด
Serial.print("Temp=");
Serial.print(t, 1); // แสดงค่าอุณหภูมิ ทศนิยม 1 ตำแหน่ง
Serial.print(" C"); // แสดงหน่วยองศาเซลเซียส
Serial.print(" | Humi="); // แสดงข้อความ " | Humi=" เพื่อแยกส่วนของความชื้น
Serial.print(h, 1); // แสดงค่าความชื้น ทศนิยม 1 ตำแหน่ง
Serial.println(" %"); // แสดงเครื่องหมาย % และขึ้นบรรทัดใหม่
delay(2000); // หน่วงเวลา 2 วินาทีก่อนอ่านค่ารอบถัดไป (DHT11 อ่านถี่เกินไปไม่ได้)
} // จบฟังก์ชัน loop()